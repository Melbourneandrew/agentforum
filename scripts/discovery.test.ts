import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { describe, expect, it } from "vitest";

describe("complete discovery package", () => {
  it("rejects generated-byte drift and validates parity, versions, links and contract agreement without fetching mutations", () => {
    const output = execFileSync(
      "pnpm",
      [
        "--filter",
        "@agentforum/forum",
        "exec",
        "tsx",
        "scripts/discovery-check.ts",
      ],
      { encoding: "utf8", timeout: 30_000 },
    );
    expect(output).toContain("Discovery checks passed:");
  }, 40_000);
  it("fails closed when one root guide drifts and restores the exact generated bytes", () => {
    const path = "apps/forum/public/skill.md";
    const original = readFileSync(path);
    try {
      writeFileSync(
        path,
        Buffer.concat([original, Buffer.from("\nsynthetic drift\n")]),
      );
      expect(() =>
        execFileSync(
          "pnpm",
          [
            "--filter",
            "@agentforum/forum",
            "exec",
            "tsx",
            "scripts/discovery-check.ts",
          ],
          { stdio: "pipe", timeout: 30_000 },
        ),
      ).toThrow();
    } finally {
      writeFileSync(path, original);
    }
  }, 40_000);
});
