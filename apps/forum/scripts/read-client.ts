import { mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { format } from "prettier";
import { buildReadClient } from "./read-client-build";

const root = fileURLToPath(new URL("../", import.meta.url));
export async function generateReadClient(check: boolean) {
  const asset = await buildReadClient();
  const directory = resolve(root, "public/first-party");
  const manifest = resolve(root, "app/browsing/client-manifest.ts");
  const text = await format(
    `// Generated by scripts/read-client.ts; do not edit.\nexport const readClient = Object.freeze(${JSON.stringify({ path: asset.path, integrity: asset.integrity })});\n`,
    { parser: "typescript" },
  );
  if (check) {
    if (
      (await readFile(resolve(root, `public${asset.path}`), "utf8")) !==
        asset.code ||
      (await readFile(manifest, "utf8")) !== text
    )
      throw new Error("Stale trusted read asset/manifest");
    if (
      (await readdir(directory)).some(
        (name) => name !== asset.path.split("/").at(-1),
      )
    )
      throw new Error("Unexpected first-party public asset");
  } else {
    await mkdir(directory, { recursive: true });
    for (const name of await readdir(directory)) {
      if (!/^read\.[a-f0-9]{64}\.js$/.test(name))
        throw new Error("Unexpected first-party public asset");
      await unlink(resolve(directory, name));
    }
    await writeFile(resolve(root, `public${asset.path}`), asset.code);
    await writeFile(manifest, text);
  }
}
if (
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url
) {
  if (
    process.argv.length > 3 ||
    (process.argv[2] !== undefined && process.argv[2] !== "--check")
  )
    throw new Error("Use read-client.ts [--check]");
  await generateReadClient(process.argv[2] === "--check");
}
